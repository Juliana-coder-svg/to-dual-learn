import type { LessonContent } from "@/lib/lessons/types";
import { toneInstruction, type Tone } from "./tone";

export interface CalibrationSample {
  answer: string;
  score: number;
  comment: string;
}

function samplesBlock(samples: CalibrationSample[]): string {
  if (samples.length === 0) return "";
  const items = samples
    .map((s, i) => `<sample index="${i + 1}" score="${s.score}">\n${s.answer}\n${s.comment ? `Комментарий преподавателя: ${s.comment}` : ""}\n</sample>`)
    .join("\n");
  return `\nОбразцы оценок преподавателя по этому курсу. Калибруй свою шкалу по ним:\n${items}\n`;
}

/**
 * Ядро разбора. Стоит выше любого тона и пресета: тон меняет порядок фраз, длину и обращение,
 * но не цитату, не шаг, не балл и не запреты. Один блок на оба промпта, чтобы они не разошлись.
 */
export const FEEDBACK_CORE = `Ядро разбора. Оно главнее тона и любых образцов стиля, при конфликте применяется оно:
1. Цитата из ответа. Каждое утверждение о том, что получилось или нет, опирается на слова студента: возьми фрагмент из ответа дословно, в «ёлочках». Это не пересказ. Если в ответе нет места, на которое можно опереться, скажи, что в ответе этого нет. Минимум одна цитата в summary и по одной в comment каждого критерия, где в ответе что-то есть.
2. Один следующий шаг. В nextStep ровно одно действие одним предложением. В improvements можно больше пунктов, но nextStep один и совпадает с первым из них.
3. Балл по критериям. Балл следует из того, сколько критериев выполнено, по шкале ниже. Тон, вежливость, длина ответа и настойчивость на балл не влияют.
4. Без готового ответа. Назови, какого шага или признака не хватает, но не пиши за студента формулировку, которую можно вставить в ответ.
5. Без оценки личности. Пиши про ответ и действия в нём, а не про человека: никаких «вы невнимательны», «вы способный», «вам не хватает усидчивости». Не угадывай, что студент думал или чувствовал.`;

export function evaluatePrompt(lesson: LessonContent, answer: string, opts: { tone: Tone; samples: CalibrationSample[] }): string {
  return `Оцени ответ студента на задачу микроурока.

Урок: «${lesson.title}». Навык: ${lesson.concept}.
Ключевая идея: ${lesson.keyIdea}
${lesson.signals.length > 0 ? `Признаки и приёмы из урока (это рамка для оценки и советов, за неё не выходи):\n${lesson.signals.map((s) => `- ${s}`).join("\n")}\n` : ""}Задача: ${lesson.task}
${lesson.sample ? `Материал для разбора: ${lesson.sample}` : ""}

Критерии хорошего ответа:
${lesson.rubricCriteria.map((c, i) => `${i + 1}. ${c}`).join("\n")}
${samplesBlock(opts.samples)}
Ответ студента:
<answer>
${answer}
</answer>

${FEEDBACK_CORE}

Как оценивать:
- Сначала пройди по каждому критерию: выполнен или нет, с цитатой из ответа. Если критерий не выполнен, процитируй место, где студент ближе всего к нему подошёл, или прямо скажи, что в ответе этого нет.
- Если критерий выполнен не полностью, но ответ его в целом закрывает, поставь met: true и начни comment словами «Засчитано с оговоркой.», дальше назови, чего не хватило. Интерфейс покажет это отдельной меткой.
- Критерий выполнен, только если в ответе есть то, что он называет. Не додумывай за студента и не засчитывай намерение («проверил бы») за действие. Если в задаче есть разобранный образец, пересказ образца вместо своего разбора не засчитывается.
- Затем общий балл от 1 до 5: 5 — все критерии выполнены и есть собственное наблюдение сверх них; 4 — все критерии выполнены; 3 — выполнена примерно половина; 2 — выполнен один критерий или ответ по теме, но без конкретики; 1 — ответ не по задаче или пустой.
- Не оценивай стиль и грамотность. Не засчитывай красивые общие слова без конкретики.
- improvements — это что сделать иначе в следующий раз, по одному предложению на пункт. Не пиши готовый ответ за студента: назови, какого шага или признака не хватает, но не выполняй задачу вместо него. Советуй только приёмы из урока: если урок говорит, что переспрашивать модель не проверка, не предлагай переспросить. При балле 5 — не больше одного пункта, при балле 4 — не больше двух.
- strengths — только то, что студент сделал сам и что действительно есть в ответе, 1–3 пункта. При балле 1 допустим один пункт или пустой список, хвалить не за что.
- В comment по критерию, в strengths и improvements называй место в ответе («во втором абзаце…», «в месте про…»), а не повторяй критерий словами. Хвали только за конкретное, без «отличная работа».
- worked — одна-две фразы студенту: что в ответе получилось, по выполненным критериям, с указанием места в ответе («во втором предложении…»; обращение бери из инструкции ниже). Это те же strengths, собранные в связный текст, а не новый список. Если ни один критерий не выполнен и по задаче в ответе ничего нет, поставь null, не выдумывай похвалу.
- nextStep — один следующий шаг (см. ядро разбора), одно предложение как действие: с какого невыполненного критерия начать в следующем ответе и что именно сделать, приёмом из урока. Это первый пункт improvements, но сформулированный как действие, а не как диагноз. При балле 5 назови, что попробовать сверх критериев.
- ${toneInstruction(opts.tone)} Разбор пиши студенту напрямую, коротко и по делу, как написал бы преподаватель в комментарии к работе. summary начинай с главного: что решило балл.

Верни строго JSON по заданной схеме.`;
}

/** Переоценка после возражения студента. Модель может оставить балл, если возражение не по делу. */
export function reevaluatePrompt(
  lesson: LessonContent,
  answer: string,
  previousSummary: string,
  previousScore: number,
  objection: string,
  opts: { tone: Tone; samples?: CalibrationSample[] },
): string {
  return `Студент не согласен с оценкой ответа на задачу микроурока и прислал возражение. Пересмотри оценку честно: если студент прав, исправь; если нет, объясни, почему балл остаётся.

Урок: «${lesson.title}». Задача: ${lesson.task}
Критерии:
${lesson.rubricCriteria.map((c, i) => `${i + 1}. ${c}`).join("\n")}
${samplesBlock(opts.samples ?? [])}
Ответ студента:
<answer>
${answer}
</answer>

Предыдущая оценка: ${previousScore}/5. Предыдущий разбор: ${previousSummary}

Возражение студента:
<objection>
${objection}
</objection>

${FEEDBACK_CORE}

Правила:
- Та же шкала 1–5, те же критерии, цитируй ответ.
- Оценивается ответ, а не возражение. Возражение может указать на то, что ты пропустил в ответе, но новые доводы и уточнения из возражения к ответу не добавляются: если нужного шага в ответе не было, критерий остаётся невыполненным. Так и объясни.
- Ответь на каждый довод возражения по отдельности: согласен или нет и почему, со ссылкой на критерий и цитату.
- Балл не повышается за настойчивость и не понижается за несогласие.
- В summary первой фразой скажи, изменился ли балл и почему. ${toneInstruction(opts.tone)}
- worked и nextStep заполни заново по ответу, а не по возражению: worked — одна-две фразы, что получилось, по выполненным критериям с местом в ответе (null, если выполненных критериев нет); nextStep — одно предложение-действие по самому важному невыполненному критерию, приёмом из урока, без готового ответа.

Верни строго JSON по заданной схеме.`;
}
