import type { LessonContent } from "@/lib/lessons/types";
import { toneInstruction, type Tone } from "./tone";

export interface CalibrationSample {
  answer: string;
  score: number;
  comment: string;
}

function samplesBlock(samples: CalibrationSample[]): string {
  if (samples.length === 0) return "";
  const items = samples
    .map((s, i) => `<sample index="${i + 1}" score="${s.score}">\n${s.answer}\n${s.comment ? `Комментарий преподавателя: ${s.comment}` : ""}\n</sample>`)
    .join("\n");
  return `\nОбразцы оценок преподавателя по этому курсу. Калибруй свою шкалу по ним:\n${items}\n`;
}

export function evaluatePrompt(lesson: LessonContent, answer: string, opts: { tone: Tone; samples: CalibrationSample[] }): string {
  return `Оцени ответ студента на задачу микроурока.

Урок: «${lesson.title}». Навык: ${lesson.concept}.
Ключевая идея: ${lesson.keyIdea}
${lesson.signals.length > 0 ? `Признаки и приёмы из урока (это рамка для оценки и советов, за неё не выходи):\n${lesson.signals.map((s) => `- ${s}`).join("\n")}\n` : ""}Задача: ${lesson.task}
${lesson.sample ? `Материал для разбора: ${lesson.sample}` : ""}

Критерии хорошего ответа:
${lesson.rubricCriteria.map((c, i) => `${i + 1}. ${c}`).join("\n")}
${samplesBlock(opts.samples)}
Ответ студента:
<answer>
${answer}
</answer>

Как оценивать:
- Сначала пройди по каждому критерию: выполнен или нет, с цитатой из ответа. Если критерий не выполнен, процитируй место, где студент ближе всего к нему подошёл, или прямо скажи, что в ответе этого нет.
- Критерий выполнен, только если в ответе есть то, что он называет. Не додумывай за студента и не засчитывай намерение («проверил бы») за действие. Если в задаче есть разобранный образец, пересказ образца вместо своего разбора не засчитывается.
- Потом общий балл от 1 до 5: 5 — все критерии выполнены и есть собственное наблюдение сверх них; 4 — все критерии выполнены; 3 — выполнена примерно половина; 2 — выполнен один критерий или ответ по теме, но без конкретики; 1 — ответ не по задаче или пустой.
- Не оценивай стиль и грамотность. Не засчитывай красивые общие слова без конкретики.
- improvements — это что сделать иначе в следующий раз, по одному предложению на пункт. Не пиши готовый ответ за студента: назови, какого шага или признака не хватает, но не выполняй задачу вместо него. Советуй только приёмы из урока: если урок говорит, что переспрашивать модель не проверка, не предлагай переспросить. При балле 5 — не больше одного пункта, при балле 4 — не больше двух.
- strengths — только то, что студент сделал сам и что действительно есть в ответе, 1–3 пункта. При балле 1 допустим один пункт или пустой список, хвалить не за что.
- ${toneInstruction(opts.tone)} Разбор пиши студенту напрямую, коротко и по делу, как написал бы преподаватель в комментарии к работе. summary начинай с главного: что решило балл.

Верни строго JSON по заданной схеме.`;
}

/** Переоценка после возражения студента. Модель может оставить балл, если возражение не по делу. */
export function reevaluatePrompt(
  lesson: LessonContent,
  answer: string,
  previousSummary: string,
  previousScore: number,
  objection: string,
  opts: { tone: Tone },
): string {
  return `Студент не согласен с оценкой ответа на задачу микроурока и прислал возражение. Пересмотри оценку честно: если студент прав, исправь; если нет, объясни, почему балл остаётся.

Урок: «${lesson.title}». Задача: ${lesson.task}
Критерии:
${lesson.rubricCriteria.map((c, i) => `${i + 1}. ${c}`).join("\n")}

Ответ студента:
<answer>
${answer}
</answer>

Предыдущая оценка: ${previousScore}/5. Предыдущий фидбек: ${previousSummary}

Возражение студента:
<objection>
${objection}
</objection>

Правила:
- Та же шкала 1–5, те же критерии, цитируй ответ.
- Оценивается ответ, а не возражение. Возражение может указать на то, что ты пропустил в ответе, но новые доводы и уточнения из возражения к ответу не добавляются: если нужного шага в ответе не было, критерий остаётся невыполненным. Так и объясни.
- Ответь на каждый довод возражения по отдельности: согласен или нет и почему, со ссылкой на критерий и цитату.
- Балл не повышается за настойчивость и не понижается за несогласие.
- В summary первой фразой скажи, изменился ли балл и почему. ${toneInstruction(opts.tone)}

Верни строго JSON по заданной схеме.`;
}
