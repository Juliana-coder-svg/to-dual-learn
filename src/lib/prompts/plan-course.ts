/** План курса до сборки уроков. Модель сама предлагает порядок и объясняет его, преподаватель правит.
 *  Про структуру модель не спрашивает: спрашивать нужно только то, что может знать один преподаватель. */
export function planCoursePrompt(opts: {
  courseTitle: string;
  description: string;
  audience: string;
  outcomes: string;
  count: number;
  /** Ответы преподавателя на уточняющие вопросы, если он на них отвечал. */
  answers?: { question: string; answer: string }[];
}): string {
  const answers = (opts.answers ?? []).filter((a) => a.answer.trim());
  return `Ты методист. Предложи план курса «${opts.courseTitle}» из ${opts.count} уроков по материалам. Уроки ещё не пишем: преподаватель сначала посмотрит план и поправит его.
Описание: ${opts.description || "не задано"}. Аудитория: ${opts.audience || "не задана"}.
${opts.outcomes.trim() ? `Образовательные результаты курса:\n${opts.outcomes.trim()}` : "Образовательные результаты не заданы."}
${answers.length ? `\nОтветы преподавателя на уточняющие вопросы:\n${answers.map((a) => `- ${a.question} Ответ: ${a.answer.trim()}`).join("\n")}\n` : ""}
Как строить план:
1. Один урок — одна идея. Идею можно назвать одной фразой. Если в материалах раздел несёт две идеи, это два урока или одна идея уходит в фон.
2. У каждого урока результат: что студент сможет сделать и что покажет в ответе. Пиши результат в третьем лице («Студент выбирает…», «Студент переписывает…»), а идею и названия нейтрально, без «ты» и «вы»: под нужное обращение уроки перепишем позже. Если образовательные результаты заданы, каждый урок работает хотя бы на один, а каждый результат закрыт хотя бы одним уроком. Результат, который ни один урок не проверяет, назови в summary.
3. Порядок от простого к сложному. Первому уроку нужен образец: в нём студент разбирает готовый пример, а не решает с нуля. Если уроков четыре и больше, последний урок на различение приёмов курса: студент выбирает, какой из них нужен в ситуации.
4. Темы не повторяются. Урок опирается на разделы материалов. Названия разделов бери дословно из материалов. Не выдумывай разделы, которых там нет.
5. Фон из материалов (история вопроса, длинные примеры, справочный текст) в уроки не бери, перечисли его в background с короткой причиной.
6. В поле why объясни, почему урок стоит на этом месте и чем он отличается от соседних. Так преподаватель сможет согласиться или переставить.
7. Не придумывай факты, имена и цифры, которых нет в материалах. Если материалов не хватает на ${opts.count} уроков, сделай меньше и скажи об этом в summary.

Верни строго JSON по заданной схеме.`;
}
