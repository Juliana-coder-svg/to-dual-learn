import type { CoursePlan } from "@/lib/lessons/types";

/** Материалы курса передаются в system вместе с этим текстом, как в остальных вызовах: пункт 7 без них не проверить.
 *  Число подсказок модель соблюдает только по тексту, при подключении обрезать hints до пяти.
 *  Подсказки по плану карточками. Уроков ещё нет, поэтому проверяется только то, что видно из плана. */
export function planHintsPrompt(opts: { courseTitle: string; audience: string; outcomes: string; plan: CoursePlan }): string {
  return `Ты методист. Посмотри на план курса «${opts.courseTitle}» (аудитория: ${opts.audience || "не задана"}) и предложи преподавателю не больше пяти улучшений. Уроки ещё не собраны.
${opts.outcomes.trim() ? `Образовательные результаты курса:\n${opts.outcomes.trim()}\n` : ""}
План:
<plan>
${JSON.stringify(opts.plan, null, 2)}
</plan>

Что проверить:
1. Результат курса, который ни один урок не проверяет, и урок, который не работает ни на один результат.
2. Два соседних урока с одной идеей или три урока подряд на пересказ и знание определений, без применения.
3. Нет урока на различение приёмов, хотя уроков четыре и больше, или он стоит не последним.
4. Первый урок построен на самостоятельном решении, образца для разбора нет.
5. В уроке две идеи, или идею нельзя назвать одной фразой.
6. Результат урока нельзя проверить по ответу студента: он звучит как «понимает», «знает», «осознаёт».
7. Урок опирается на раздел, которого нет в материалах, или важный раздел материалов не попал ни в урок, ни в фон.

Правила подсказок:
- Подсказка только по тому, что видно в плане. Каждая называет урок или «Курс» и точное место в плане.
- Пиши для преподавателя, который видит план как список уроков с идеей, результатом и опорой: называй «идея урока», «результат урока», «опора на материалы», а не имена полей. Кавычки с названиями полей и JSON в подсказках не нужны.
- Одно предложение на проблему, одно на действие. Действие — правка плана, а не готовый текст урока.
- Если всё в порядке, верни пустой список. Не добирай подсказки до пяти.
- Не хвали план. Преподавателю нужны только места для правки.

Верни строго JSON по заданной схеме.`;
}
