/** Режим «вместе с преподавателем»: перед сборкой уроков модель задаёт 3–5 вопросов о целях, аудитории и акцентах.
 *  Ответы сохраняются как материал курса и попадают во все последующие промпты. */
export function clarifyCoursePrompt(opts: { courseTitle: string; description: string; audience: string; outcomes: string }): string {
  return `Преподаватель загрузил материалы курса «${opts.courseTitle}» и хочет собрать из них короткие уроки.
Описание: ${opts.description || "не задано"}. Аудитория: ${opts.audience || "не задана"}.
${opts.outcomes.trim() ? `Образовательные результаты:\n${opts.outcomes.trim()}` : "Образовательные результаты не заданы."}

Прочитай материалы и задай преподавателю от 3 до 5 вопросов, ответы на которые изменят уроки. Спрашивай то, что знает только он: на каком уровне аудитория и что она уже умеет; какие ошибки студентов он видит чаще всего; какие примеры из его практики можно взять в задачи; что в материалах главное, а что фон; чего в уроках быть не должно. Если аудитория или результаты не заданы, первый вопрос задай о них.

Как спрашивать:
- Один вопрос — одна вещь. Не склеивай два вопроса в один. Вопрос не длиннее 25 слов. Преподаватель отвечает в поле формы, и ответ должен уместиться в два-три предложения.
- Не спрашивай, как строить уроки: порядок, число уроков, какой раздел сделать итоговым. Это ты решишь сам по материалам.
- Не спрашивай то, что уже есть в описании и результатах.
- Примеры в вопросе давай, только если без них вопрос непонятен, и не больше двух.
- К каждому вопросу добавь короткую пометку: что изменится в уроках от ответа.

Верни строго JSON по заданной схеме.`;
}
