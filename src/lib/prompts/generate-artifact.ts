import type { ArtifactKind } from "@/lib/lessons/types";

const KIND_INSTRUCTIONS: Record<ArtifactKind, string> = {
  assignment:
    "Составь задание для студентов: цель, формулировка, что сдать, критерии оценки (3–5 пунктов), ориентир по времени.",
  quiz:
    "Составь проверочный тест на 8–10 вопросов: вопросы с вариантами ответов (4 варианта, один верный) и 2 открытых вопроса. В конце — ключ с краткими пояснениями, почему верен именно этот вариант.",
  notes:
    "Составь конспект по материалам: структура по разделам, ключевые определения, примеры, типичные ошибки. Конспект должен читаться за 10 минут.",
  lesson_plan:
    "Составь план занятия на 80 минут: цель и образовательные результаты, тайминг по блокам, что делает преподаватель и что делают студенты, практическая часть не меньше 60% времени, домашнее задание.",
  presentation:
    "Составь структуру презентации: 10–14 слайдов, для каждого — заголовок, 2–4 тезиса и заметка спикеру. Один слайд = одна мысль.",
};

export function generateArtifactPrompt(opts: {
  kind: ArtifactKind;
  courseTitle: string;
  audience: string;
  instructions: string;
}): string {
  return `${KIND_INSTRUCTIONS[opts.kind]}
Курс: «${opts.courseTitle}». Аудитория: ${opts.audience || "не задана"}.
Пожелания преподавателя: ${opts.instructions.trim() || "нет"}.

Опирайся на материалы курса. Формат ответа — Markdown, без вступления и без заключительных фраз.`;
}
