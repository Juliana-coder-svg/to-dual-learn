/** Документы для студентов: задание и тест. Конспект, план и презентация — для преподавателя. */
const STUDENT_FACING: ArtifactKind[] = ["assignment", "quiz"];

export function generateArtifactPrompt(opts: {
  kind: ArtifactKind;
  courseTitle: string;
  audience: string;
  instructions: string;
}): string {
  const readerRule = STUDENT_FACING.includes(opts.kind)
    ? "Документ прочитают студенты, у которых нет материалов курса. Не отсылай к «разделу 3» или «методичке»: то, на что опирается документ, перескажи в нём самом коротко, в одном-двух абзацах или в примере, а не как конспект."
    : "Документ для преподавателя: ссылаясь на материалы, называй конкретный материал и раздел.";
  return `${KIND_INSTRUCTIONS[opts.kind]}
Курс: «${opts.courseTitle}». Аудитория: ${opts.audience || "не задана"}.
Пожелания преподавателя: ${opts.instructions.trim() || "нет"}.

Опирайся на материалы курса. ${readerRule} Примеры ответов и реплик пиши без форм прошедшего времени от первого лица («посмотрел», «проверила»): пол автора неизвестен. Оформление простое: заголовки и списки, без вступления и заключительных фраз. Пиши как преподаватель, а не как автор рекламного буклета.`;
}
