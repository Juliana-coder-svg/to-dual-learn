  lesson_plan:
    "Составь план занятия на 80 минут, до 1500 слов: цель и образовательные результаты, блоки с минутами на каждый, что делают преподаватель и студенты в каждом блоке, домашнее задание. Практика занимает не меньше 60% времени. У каждого практического блока проверяемый результат: что студенты сдают или показывают к концу блока.",
