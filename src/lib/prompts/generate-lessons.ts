import { toneInstruction, type Tone } from "./tone";

export function generateLessonsPrompt(opts: {
  courseTitle: string;
  courseDescription: string;
  audience: string;
  outcomes: string;
  tone: Tone;
  count: number;
  existingTitles: string[];
}): string {
  const existing =
    opts.existingTitles.length > 0
      ? `\nВ курсе уже есть уроки: ${opts.existingTitles.join("; ")}. Не повторяй их темы, продолжай последовательность.`
      : "";
  const outcomes = opts.outcomes.trim()
    ? `\nОбразовательные результаты курса (каждый урок должен работать хотя бы на один из них):\n${opts.outcomes.trim()}`
    : "";
  const first = opts.existingTitles.length === 0;
  const scaffold = first
    ? `- Опора снижается от урока к уроку. В первом уроке курса в sample есть разобранный образец: один элемент уже решён так, как ты ждёшь от студента, а задача просит разобрать остальные так же. В следующих уроках образца нет, но задача структурирована. В последних уроках задача открытая.`
    : `- Это продолжение курса: образец разбора в sample не нужен, задачи открытые, опора ниже, чем в первых уроках курса.`;
  const mixed =
    first && opts.count >= 4
      ? `\n- Последний урок курса — на различение: в sample 4–5 коротких ситуаций, в задаче нужно выбрать, какой приём из предыдущих уроков применить к каждой, и объяснить почему. Приёмы в задаче назови своими словами, не номерами уроков.`
      : "";
  return `Собери ${opts.count} микроуроков по 5 минут для курса «${opts.courseTitle}».
Описание курса: ${opts.courseDescription || "не задано"}.
Аудитория: ${opts.audience || "взрослые, которые учатся по 5 минут в день"}.${outcomes}${existing}
${toneInstruction(opts.tone)}

Правила:
- Каждый урок отрабатывает один конкретный навык или идею из материалов курса, в логичной последовательности от простого к сложному.
- intro и keyIdea опираются на материалы: термины, примеры, формулировки — оттуда. Если в материалах чего-то нет, не выдумывай, бери соседнюю тему, которая есть.
- Студент материалов не видит, он видит только урок. Поэтому не пиши «как сказано в методичке» или «три вопроса из материалов»: назови эти вопросы, шаги и признаки прямо в уроке, в signals или в задаче.
- task — открытая практическая задача, где нужно что-то разобрать, найти, переписать или решить, применив идею урока к новому материалу. Задачу нельзя выполнить, пересказав keyIdea или скопировав signals. Если для задачи нужен текст или пример, положи его в sample; иначе sample = null.
- Размер задачи: ответ помещается в 6–10 предложений. Считай объём как число элементов в sample, умноженное на число вопросов к каждому: 5 утверждений с тремя вопросами к каждому — это 15 ответов, в 5 минут не уложиться. Держи не больше 8 ответов на задачу: например, 4 элемента по 2 вопроса или 2 элемента по 3–4 вопроса.
${scaffold}${mixed}
- Если пример в sample придуман, а не взят из материалов, начни его со слов «Условный пример:», чтобы студент не искал его в материалах.
- intro начинается с ситуации из практики студента или с ошибки, которую урок чинит, а не с определения термина. keyIdea звучит так, как преподаватель сказал бы вслух на занятии: что делать и при каком условии, без «важно понимать».
- rubricCriteria — 3–4 проверяемых критерия, по которым наставник оценит ответ. Критерий проверяем, если по ответу можно однозначно сказать «выполнен» или «нет»: называй, что именно должно быть в ответе (какой элемент, какой признак, какой шаг), а не «тема раскрыта». Критерии не дублируют друг друга. Один критерий — на объяснение: почему студент решил именно так.
- flashcards — 2–3 карточки на припоминание, а не на узнавание. Вопрос требует вспомнить и применить, ответ нельзя угадать по формулировке вопроса. Не «что такое X?», а «по каким признакам ты поймёшь, что перед тобой X?». Первая карточка — на признаки или шаги приёма, вторая — на применение к короткой новой ситуации, которой в уроке не было, третья — на типичную ошибку: что человек сделал не так и почему.
- Язык: русский, живой, без штампов из системной инструкции. Заголовок урока — как назвал бы его преподаватель, а не рекламный слоган.

Верни строго JSON по заданной схеме.`;
}
