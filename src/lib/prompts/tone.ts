export type Tone = "ty" | "vy";

/** Как обращаться к студенту. «ты» - взрослые на открытых курсах, «вы» - вузы, школы, корпоративные программы. */
export function toneInstruction(tone: Tone): string {
  return tone === "vy"
    ? "Обращайся к студенту на «вы», ровно и уважительно, без канцелярита."
    : "Обращайся к студенту на «ты», прямо и спокойно, как коллега по работе, без сюсюканья, шуток и панибратства.";
}
