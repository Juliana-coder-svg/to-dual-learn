import type { LessonContent } from "@/lib/lessons/types";
import { toneInstruction, type Tone } from "./tone";

/** Второй проход: агент-методист сверяет уроки с материалами и результатами, правит, что можно, остальное помечает. */
export function reviewLessonsPrompt(opts: {
  courseTitle: string;
  audience: string;
  outcomes: string;
  tone: Tone;
  lessons: LessonContent[];
  /** Сколько уроков в курсе уже было до этой пачки. 0 — проверяется курс с начала. */
  existingCount?: number;
}): string {
  const existing = opts.existingCount ?? 0;
  const scaffoldRule =
    existing === 0
      ? `5. Опора снижается по ходу курса: в первом уроке в sample есть разобранный образец (один элемент решён так, как ждут от студента), в последних уроках задача открытая. Если в первом уроке образца нет - добавь его и перестрой задачу «разбери остальные так же».`
      : `5. Это уроки, добавленные к курсу, в котором уже ${existing} ${existing === 1 ? "урок" : existing < 5 ? "урока" : "уроков"}: образец в sample им не нужен, задачи должны быть открытыми, опора ниже, чем в начале курса. Если образец есть - убери его и сделай задачу самостоятельной.`;
  const mixRule =
    existing === 0
      ? `8. Нет повторов между уроками, последовательность от простого к сложному. Если уроков четыре и больше, а задачи на различение приёмов из разных уроков нет, предложи во flags последнего урока, как её добавить, но сам структуру урока не ломай.`
      : `8. Нет повторов внутри пачки. Прежние уроки курса ты не видишь, поэтому повторы с ними не предполагай и задачу на различение не требуй.`;
  return `Ты методист-ревьюер. Проверь уроки курса «${opts.courseTitle}» (аудитория: ${opts.audience || "не задана"}).
${opts.outcomes.trim() ? `Образовательные результаты курса:\n${opts.outcomes.trim()}\n` : ""}${toneInstruction(opts.tone)}

Уроки на проверку:
<lessons>
${JSON.stringify(opts.lessons, null, 2)}
</lessons>

Проверь каждый урок по пунктам:
1. Опора на материалы: все термины, примеры и утверждения есть в материалах курса. Что не подтверждается - убери или замени тем, что есть. Утверждения о том, как «обычно» или «часто» бывает, без опоры в материалах смягчи или убери.
2. Образовательные результаты: урок работает хотя бы на один результат, если результаты заданы.
3. Студент видит только урок, материалов у него нет. Отсылки вроде «три вопроса из методички» или «процедура из материалов» замени на сами вопросы, шаги или признаки, прямо в тексте урока.
4. Задача выполнима за 3-5 минут: ответ помещается в 6-10 предложений, элементов в sample не больше 5-6, а число элементов, умноженное на число вопросов к каждому, не больше 8. Если больше - сократи элементы или вопросы. У задачи открытый ответ, который нельзя собрать из keyIdea или signals без обращения к sample.
${scaffoldRule}
6. Критерии проверяемы: по ответу можно однозначно сказать «выполнен» или «нет», в критерии названо, что именно должно быть в ответе. Размытые («хорошо раскрыта тема») перепиши. Критерии не дублируют друг друга, каждый вытекает из того, о чём просит задача, и один из них - на объяснение, почему студент решил так. Там, где допустимы разные верные ответы, перечисли их в критерии, чтобы наставник не снижал балл за равнозначное решение.
7. Карточки на припоминание, не на узнавание: вопрос требует вспомнить признаки или шаги и применить их, ответ нельзя угадать по формулировке вопроса. Карточку «что такое X?» перепиши. Среди карточек должна быть одна на новую короткую ситуацию, которой в уроке не было, и одна на типичную ошибку.
${mixRule}
9. Тон и язык соответствуют аудитории, нет AI-клише и воды.

Правь прямо в тексте уроков, не меняя их количество и порядок. В notes для каждого урока укажи, менял ли ты его и какие проблемы нашел, с номером пункта. Если проблему нельзя починить без преподавателя (например, в материалах нет нужной темы), оставь урок как есть и опиши это во flags.

Верни строго JSON по заданной схеме.`;
}
