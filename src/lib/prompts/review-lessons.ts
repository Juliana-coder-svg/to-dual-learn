import type { LessonContent } from "@/lib/lessons/types";
import { toneInstruction, type Tone } from "./tone";

/** Второй проход: агент-методист сверяет уроки с материалами и результатами, правит, что можно, остальное помечает. */
export function reviewLessonsPrompt(opts: {
  courseTitle: string;
  audience: string;
  outcomes: string;
  tone: Tone;
  lessons: LessonContent[];
}): string {
  return `Ты методист-ревьюер. Проверь уроки курса «${opts.courseTitle}» (аудитория: ${opts.audience || "не задана"}).
${opts.outcomes.trim() ? `Образовательные результаты курса:\n${opts.outcomes.trim()}\n` : ""}${toneInstruction(opts.tone)}

Уроки на проверку:
<lessons>
${JSON.stringify(opts.lessons, null, 2)}
</lessons>

Проверь каждый урок по пунктам:
1. Опора на материалы: все термины, примеры и утверждения есть в материалах курса. Что не подтверждается — убери или замени тем, что есть.
2. Образовательные результаты: урок работает хотя бы на один результат, если результаты заданы.
3. Задача выполнима за 3–5 минут, у неё открытый ответ, который можно оценить по критериям.
4. Критерии проверяемы: по ответу можно однозначно сказать «выполнен» или «нет». Размытые («хорошо раскрыта тема») перепиши.
5. Нет повторов между уроками, последовательность от простого к сложному.
6. Тон и язык соответствуют аудитории, нет AI-клише и воды.

Правь прямо в тексте уроков, не меняя их количество и порядок. В notes для каждого урока укажи, менял ли ты его и какие проблемы нашёл. Если проблему нельзя починить без преподавателя (например, в материалах нет нужной темы), оставь урок как есть и опиши это во flags.

Верни строго JSON по заданной схеме.`;
}
