import { toneInstruction, type Tone } from "./tone";

export function checkHomeworkPrompt(opts: {
  task: string;
  criteria: string;
  submissions: { student: string; answer: string }[];
  tone: Tone;
}): string {
  const items = opts.submissions
    .map(
      (s, i) => `<submission index="${i + 1}" student="${s.student.replace(/"/g, "'")}">\n${s.answer}\n</submission>`,
    )
    .join("\n\n");
  return `Проверь домашние работы студентов.

Задание:
${opts.task}

Критерии проверки от преподавателя:
${opts.criteria}

Работы:
${items}

Как проверять:
- ${toneInstruction(opts.tone)}
- По каждой работе пройди по всем критериям: выполнен или нет, с цитатой. Критерий выполнен, только если в работе есть то, что он называет; намерение («проверил бы») и общие слова не засчитывай.
- Балл от 0 до 10 по доле выполненных критериев: все выполнены — 8–10 (10 только при собственном наблюдении сверх критериев), примерно половина — 4–6, один — 2–3, пустая работа или не по заданию — 0–1. Одна и та же доля у разных студентов даёт один и тот же балл.
- Отметь в flags, если работа дословно повторяет материалы, повторяет другую работу, или написана не по теме.
- Комментарий студенту — 2–4 предложения, с конкретикой, как замечание преподавателя на полях работы: одно, что сделано верно, и один-два шага, что сделать иначе. Не пиши за студента готовый ответ, назови недостающий шаг или признак. Сроки, формат пересдачи и время на работу не придумывай: если в задании их нет, не называй.
- В flags только то, что видно по тексту: дословные совпадения с материалами или с другой работой, пустая работа, работа не по заданию. Догадки вроде «похоже на пересказ теории» в flags не ставь, пиши их в комментарий.
- overview для преподавателя заполняй после всех работ и только по ним, не по общим соображениям:
  - failedCriteria: критерии, которые не выполнила половина работ или больше, по убыванию числа провалов. criterion дословно как у преподавателя, failed — сколько работ его не выполнили, total — сколько работ проверено. Если каждый критерий выполнило большинство, оставь список пустым.
  - reteach: 1–3 пункта, что переобъяснить на занятии. topic — какой фрагмент материалов или какая идея: раздел, правило или приём так, как он назван в материалах курса; если материалов нет, идея из задания. why — почему это видно по работам: одно-два предложения с примером из одной-двух работ, с именем студента. Не переобъяснять то, что провалила одна работа из многих.
  - quickWins: что уже получается у большинства, 1–3 пункта по критериям, выполненным в большинстве работ, коротко, без похвалы ради похвалы. Если таких критериев нет, пустой список.
- Поле student в результате должно точно совпадать с атрибутом student работы.

Верни строго JSON по заданной схеме.`;
}
